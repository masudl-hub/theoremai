/**
 * Writes two modules from the bundled egress patterns
 * (`src/guardrails/egress-patterns.ts`):
 *
 * - `src/guardrails/injection-reversed.ts`, `REVERSED_INJECTION_PATTERNS`: each
 *   injection pattern reversed, so text written backwards is matched as written.
 * - `src/guardrails/egress-automata.ts`, `FORWARD_AUTOMATON` / `REVERSED_AUTOMATON`:
 *   for each pattern, an automaton accepting every match of it and more, which
 *   the streaming hold runs to see where a match could still be under way
 *   (`egress-stream.ts`). They are most of the kernel's size, so the stream loads
 *   them on first use (`loadEgressAutomata`).
 *
 * The automata are built as `src/guardrails/egress-compiler.ts` describes.
 *
 *   deno run --allow-read --allow-write --allow-run scripts/gen-egress-automata.ts
 *
 * @module
 */

import { bundledEgressAutomata } from '../src/guardrails/egress-compiler.ts';
import type { AutomatonData } from '../src/guardrails/host-patterns.ts';

const AUTOMATA = new URL('../src/guardrails/egress-automata.ts', import.meta.url);
const REVERSED = new URL('../src/guardrails/injection-reversed.ts', import.meta.url);

const HEADER = `/**
 * Generated by \`scripts/gen-egress-automata.ts\` from \`egress-patterns.ts\`.
 * Do not edit: change the patterns and run the script.
 *
 * @module
 */
`;

function reversedText(data: ReturnType<typeof bundledEgressAutomata>): string {
  return `${HEADER}
/** Each injection pattern reversed: it matches where the pattern matches the text written backwards. */
const REVERSED_INJECTION_PATTERNS: RegExp[] = [
${data.reversedPatterns.map((re) => `  ${re.toString()},`).join('\n')}
];

export { REVERSED_INJECTION_PATTERNS };
`;
}

function automataText(data: ReturnType<typeof bundledEgressAutomata>): string {
  const table = (value: AutomatonData): string =>
    `{\n  classStarts: ${JSON.stringify(value.classStarts)},\n  charsets: ${JSON.stringify(value.charsets)},\n  initials: ${JSON.stringify(value.initials)},\n  leads: ${JSON.stringify(value.leads)},\n  nodes: ${JSON.stringify(value.nodes)},\n}`;
  return `${HEADER}
import type { AutomatonData } from './host-patterns.ts';

/** Every egress pattern, loosened to a superset automaton, in \`EGRESS_PATTERNS\` order. */
const FORWARD_AUTOMATON: AutomatonData = ${table(data.forward)};

/** Each reversed injection pattern, loosened the same way. */
const REVERSED_AUTOMATON: AutomatonData = ${table(data.reversed)};

export { FORWARD_AUTOMATON, REVERSED_AUTOMATON };
`;
}

if (import.meta.main) {
  const data = bundledEgressAutomata();
  await Deno.writeTextFile(AUTOMATA, automataText(data));
  await Deno.writeTextFile(REVERSED, reversedText(data));
  const fmt = new Deno.Command('npx', {
    args: ['biome', 'format', '--write', AUTOMATA.pathname, REVERSED.pathname],
    stdout: 'inherit',
    stderr: 'inherit',
  });
  if (!(await fmt.output()).success) Deno.exit(1);
}
